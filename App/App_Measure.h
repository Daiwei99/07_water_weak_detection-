#ifndef __MEASURE_H
#define __MEASURE_H

#include "stm32f10x.h"
#include "Int_Wire.h"

/*==============================================================================
 * 测量与判定层（阶段一：原理验证）
 *
 * 职责：按需求文档《四、电压测量总表》依次采集 V1~V10，做断线/水浸判定，
 *       并计算水浸点距离 L1。
 *
 * 依赖：Bsp_Wire（建立通路）+ Bsp_Adc（采电压），本层不直接碰 GPIO 和寄存器。
 *
 *------------------------------------------------------------------------------
 * 【V1~V10 的完整定义】逐行抄自需求文档电压测量总表，并已与原理图的 4052
 * 接线核对一致。表里"ADC0/ADC1"是原理图网络名：ADC0=PA1，ADC1=PA2。
 *
 *  项目      开关(红黄绿黑)      4052通道               ADC0        ADC1
 *  ------    ---------------     -------------------    --------    --------
 *  断线1     1 1 0 0             0 YELLOW_BLACK         V2 黄线     V1 黑线
 *  断线2     1 1 0 0             2 RED_GREEN            V4 红线     V3 绿线
 *  水浸      1 0 0 1             1 GREEN_YELLOW         V6 绿线     V5 黄线
 *  定位1     0 1 1 0             1 GREEN_YELLOW         V8 绿线     V7 黄线
 *  定位2a    1 0 0 1             2 RED_GREEN            V9 红线     （不用）
 *  定位2b    1 0 0 1             0 YELLOW_BLACK        （不用）     V10 黑线
 *
 * 注意"断线1"和"断线2"开关状态完全相同（红黄都供电），只是 4052 通道不同，
 * 所以这两项可以共用一次通路建立，省一次 15ms 等待。但为了让代码和文档
 * 逐行对得上、便于排错，这里仍然分别 Apply，宁可慢一点。
 *
 * 定位2 特殊：V9 和 V10 开关状态相同（红供电、黑接R11），只切 4052 通道。
 * 因为 4052 两个 bank 共用地址线，没法一次同时把 ADC0 接红线、ADC1 接黑线。
 *============================================================================*/

/*------------------------------------------------------------------------------
 * 十个电压值，单位统一用毫伏（int32_t）
 *
 * 【为什么用整数毫伏而不用 float】
 *   1) 打印安全：Keil MicroLIB 的 printf 对 %f 支持不稳定，浮点打不出来时
 *      现象是"整行没输出"或"打出乱码"，很容易误判成 ADC 没采到值。整数 %d
 *      不存在这个问题。
 *   2) 精度够用：内部 12bit ADC 在 3.3V 量程下 1 LSB = 0.806mV，毫伏为单位
 *      已经比 ADC 本身的分辨率细，不损失信息。
 *   仅在算 L1 时才转成 float，因为公式里有除法。
 *----------------------------------------------------------------------------*/
typedef struct
{
    int32_t v1;      /* 黑线电压，断线监测1 */
    int32_t v2;      /* 黄线电压，断线监测1 */
    int32_t v3;      /* 绿线电压，断线监测2 */
    int32_t v4;      /* 红线电压，断线监测2 */
    int32_t v5;      /* 黄线电压，水浸监测 */
    int32_t v6;      /* 绿线电压，水浸监测 */
    int32_t v7;      /* 黄线电压，水浸定位1 */
    int32_t v8;      /* 绿线电压，水浸定位1 */
    int32_t v9;      /* 红线电压，水浸定位2 */
    int32_t v10;     /* 黑线电压，水浸定位2 */
} MeasVolt_t;

/*------------------------------------------------------------------------------
 * 判定阈值（单位 mV）
 *
 * 这几个值是阶段一必须实测标定的参数，现在给的是有依据的初值，不是拍脑袋：
 *
 * MEAS_EQUAL_TOL_MV：判断"V1 == V2"的容差。
 *   两路电压走的是不同的 4052 通道和不同的 ADC 引脚，即使被测点电压相同，
 *   也会有通道导通电阻差异（4052 典型 Ron 差几十Ω）、2kΩ 保护电阻偏差、
 *   ADC 通道间失配。50mV 约 1.5% 满量程，先按这个跑，实测后收紧。
 *
 * MEAS_ZERO_MV：判断"V ≈ 0"（确认断线）。
 *   浮空引脚经 2kΩ 到 ADC，理论上读到接近 0，留 100mV 给漏电流和噪声。
 *
 * MEAS_FULL_MV：判断"V ≈ 3.3V"（无水浸时绿线应该是满幅）。
 *   3300 - 100 = 3200mV。供电侧串了 100Ω(R12/R16)，无水浸时取样支路无电流，
 *   压降为 0，所以确实应该读到接近满幅。
 *----------------------------------------------------------------------------*/
#define MEAS_EQUAL_TOL_MV   50
#define MEAS_ZERO_MV        100
#define MEAS_FULL_MV        3200
#define MEAS_VCC_MV         3300        /* 供电电压，公式里的 3.3V */

/*------------------------------------------------------------------------------
 * 故障状态
 *----------------------------------------------------------------------------*/
typedef enum
{
    FAULT_NONE       = 0,       /* 正常 */
    FAULT_BREAK_RED  = 0x01,    /* 红线回路断（V3 != V4） */
    FAULT_BREAK_YEL  = 0x02,    /* 黄线回路断（V1 != V2） */
    FAULT_LEAK       = 0x04     /* 水浸 */
} FaultFlag_t;

/*------------------------------------------------------------------------------
 * 线缆参数。阶段一要标定的另外两个值。
 *
 * MEAS_R_SAMPLE_OHM = 4000：公式里的常数。对应原理图 R11 = 3.9kΩ 取整。
 *   为什么公式用 4000 而实物是 3900：需求文档给的公式就是 4000，先照抄跑通，
 *   等实测偏差出来再决定是改成 3900 还是保持 4000（有可能公式推导时把
 *   4052 通道电阻和 2k 保护电阻也算进去了，那 4000 反而更准）。
 *   这是阶段一要回答的问题之一，别提前"优化"。
 *
 * r：线缆单位长度电阻 Ω/m。必须实测：量一段已知长度线缆的直流电阻算出来。
 * L：线缆总长度 m。按实际接的线缆填。
 *----------------------------------------------------------------------------*/
#define MEAS_R_SAMPLE_OHM   4000.0f

/* 默认值只是为了让程序能跑起来，实测前算出的 L1 没有意义 */
#define MEAS_DEFAULT_R      0.1f        /* Ω/m ★待实测标定 */
#define MEAS_DEFAULT_L      100.0f      /* m    ★按实际线缆填 */

void Measure_Init(void);

/* 设置线缆参数，后期由屏幕菜单调用 */
void  Measure_SetCableParam(float r_ohm_per_m, float length_m);
float Measure_GetR(void);
float Measure_GetL(void);

/*--- 分项采集，阶段二按需单独调用 ------------------------------------------*/
void Measure_ReadBreak(MeasVolt_t *v);     /* 采 V1~V4 */
void Measure_ReadLeak(MeasVolt_t *v);      /* 采 V5、V6 */
void Measure_ReadLocate(MeasVolt_t *v);    /* 采 V7~V10 */

/* 阶段一：一次采完 V1~V10 */
void Measure_ReadAll(MeasVolt_t *v);

/*--- 判定 -------------------------------------------------------------------*/

/* 判定结果结构（阶段二用） */
typedef struct
{
    uint8_t  break_detected;    /* 1 = 检测到断线 */
    uint8_t  leak_detected;     /* 1 = 检测到水浸 */
    uint8_t  pos_valid;         /* 1 = 定位结果有效 */
    int32_t  pos_mm;            /* 定位距离（毫米） */
    const char *break_line;     /* 断线的线路名称，如 "黄线回路" */
    uint8_t  fault_flags;       /* FaultFlag_t 组合，供显示层判断哪条线断，避免比较中文字符串 */
} MeasResult_t;

uint8_t Measure_CheckBreak(const MeasVolt_t *v);   /* 返回 FaultFlag_t 组合 */
uint8_t Measure_CheckLeak(const MeasVolt_t *v);    /* 1 = 有水浸 */

/*------------------------------------------------------------------------------
 * 计算水浸点距离
 * @param  v      已采集好的电压表（需要 v5,v6,v9,v10）
 * @param  out_mm 输出距离，单位毫米
 * @return 1 = 算出有效结果，0 = 数据不满足计算条件（见 .c 里的说明）
 *
 * 用毫米做输出单位同样是为了避免浮点打印。
 *----------------------------------------------------------------------------*/
uint8_t Measure_CalcL1(const MeasVolt_t *v, int32_t *out_mm);

/* 阶段二：综合判定（断线 + 水浸 + 定位），一次性返回所有结果 */
void Measure_Judge(const MeasVolt_t *v, MeasResult_t *result);

/*--- 输出 -------------------------------------------------------------------*/
/* 把 V1~V10 打到调试串口，阶段一验证时对着这个表看 */
void Measure_PrintVolt(const MeasVolt_t *v);

/* 打印判定结果和定位距离 */
void Measure_PrintResult(const MeasVolt_t *v);

#endif /* __MEASURE_H */
