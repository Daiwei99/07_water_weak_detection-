const uint8_t* FontCN_GetData(const char *utf8)
{
    if (utf8 == NULL)
        return NULL;

    for (uint16_t i = 0; i < FONT_CN_COUNT; i++)
    {
        if (memcmp(utf8, s_font_table[i].utf8, 3) == 0)
        {
            return s_font_table[i].data;
        }
    }

    return NULL;  // 未找到
}
