#ifndef __INT_RS485_H
#define __INT_RS485_H

#include "stm32f10x.h"

/*==============================================================================
 * RS485 通信接口
 *
 * 硬件：USART3 (PB10=TX, PB11=RX) + MAX13487（自动方向控制）
 *
 * MAX13487 的特点：
 *   - 不需要 DE/RE 引脚控制方向，芯片内部自动检测 TX 数据边沿切换收发。
 *   - 发送时自动使能驱动器，发完自动切回接收。
 *   - 从软件角度看就是个普通 UART，不用管半双工时序。
 *
 * 波特率：9600（工业现场常用，抗干扰强）
 * 格式：8-N-1
 *
 * 阶段二用途：循环输出监测状态和定位结果，格式待定（JSON 或固定帧）。
 *============================================================================*/

void Rs485_Init(void);

/* 发送一个字节，阻塞直到发完 */
void Rs485_SendByte(uint8_t byte);

/* 发送字符串 */
void Rs485_SendString(const char *str);

/* 发送指定长度的数据 */
void Rs485_SendData(const uint8_t *data, uint16_t len);

#endif /* __INT_RS485_H */
