/* ========== 软件I2C引脚操作 ========== */

// 引脚宏定义（来自Com_Board.h，如果没有需要补充）
#define OLED_SCL_PORT   GPIOB
#define OLED_SCL_PIN    GPIO_Pin_1
#define OLED_SDA_PORT   GPIOB
#define OLED_SDA_PIN    GPIO_Pin_2

#define OLED_SCL_H()    GPIO_SetBits(OLED_SCL_PORT, OLED_SCL_PIN)
#define OLED_SCL_L()    GPIO_ResetBits(OLED_SCL_PORT, OLED_SCL_PIN)
#define OLED_SDA_H()    GPIO_SetBits(OLED_SDA_PORT, OLED_SDA_PIN)
#define OLED_SDA_L()    GPIO_ResetBits(OLED_SDA_PORT, OLED_SDA_PIN)
#define OLED_SDA_READ() GPIO_ReadInputDataBit(OLED_SDA_PORT, OLED_SDA_PIN)

/* I2C 延时（约5us，对应100kHz） */
static void I2C_Delay(void)
{
    uint8_t i = 10;
    while (i--);
}

/* ========== 软件I2C时序 ========== */

static void I2C_Start(void)
{
    OLED_SDA_H();
    OLED_SCL_H();
    I2C_Delay();
    OLED_SDA_L();
    I2C_Delay();
    OLED_SCL_L();
}

static void I2C_Stop(void)
{
    OLED_SDA_L();
    OLED_SCL_H();
    I2C_Delay();
    OLED_SDA_H();
    I2C_Delay();
}

static void I2C_WriteByte(uint8_t dat)
{
    uint8_t i;
    for (i = 0; i < 8; i++)
    {
        if (dat & 0x80)
            OLED_SDA_H();
        else
            OLED_SDA_L();

        I2C_Delay();
        OLED_SCL_H();
        I2C_Delay();
        OLED_SCL_L();
        dat <<= 1;
    }

    // 等待ACK
    OLED_SDA_H();
    I2C_Delay();
    OLED_SCL_H();
    I2C_Delay();
    OLED_SCL_L();
}

/* ========== SSD1306命令与数据写入 ========== */

static void Oled_WriteCmd(uint8_t cmd)
{
    I2C_Start();
    I2C_WriteByte(OLED_I2C_ADDR);
    I2C_WriteByte(0x00);  // 命令模式
    I2C_WriteByte(cmd);
    I2C_Stop();
}

static void Oled_WriteData(uint8_t dat)
{
    I2C_Start();
    I2C_WriteByte(OLED_I2C_ADDR);
    I2C_WriteByte(0x40);  // 数据模式
    I2C_WriteByte(dat);
    I2C_Stop();
}

