// 字库索引：ASCII码 - 0x20
#define FONT_INDEX(ch)  ((ch) - 0x20)

/* ========== 初始化 ========== */

void Oled_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStructure;

    // 使能GPIO时钟
    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOB, ENABLE);

    // 配置SCL和SDA为开漏输出
    GPIO_InitStructure.GPIO_Pin = OLED_SCL_PIN | OLED_SDA_PIN;
    GPIO_InitStructure.GPIO_Mode = GPIO_Mode_Out_OD;
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(GPIOB, &GPIO_InitStructure);

    OLED_SCL_H();
    OLED_SDA_H();

    Delay_ms(100);  // 等待OLED上电稳定

    // SSD1306初始化序列
    Oled_WriteCmd(0xAE);  // 关闭显示
    Oled_WriteCmd(0x20);  // 设置内存地址模式
    Oled_WriteCmd(0x10);  // 页地址模式
    Oled_WriteCmd(0xB0);  // 设置页起始地址
    Oled_WriteCmd(0xC8);  // 设置COM扫描方向
    Oled_WriteCmd(0x00);  // 设置列低位地址
    Oled_WriteCmd(0x10);  // 设置列高位地址
    Oled_WriteCmd(0x40);  // 设置起始行地址
    Oled_WriteCmd(0x81);  // 设置对比度
    Oled_WriteCmd(0xFF);  // 对比度值
    Oled_WriteCmd(0xA1);  // 设置段重映射
    Oled_WriteCmd(0xA6);  // 正常显示
    Oled_WriteCmd(0xA8);  // 设置复用比
    Oled_WriteCmd(0x3F);  // 1/64 duty
    Oled_WriteCmd(0xA4);  // 全局显示开启
    Oled_WriteCmd(0xD3);  // 设置显示偏移
    Oled_WriteCmd(0x00);  // 无偏移
    Oled_WriteCmd(0xD5);  // 设置时钟分频
    Oled_WriteCmd(0xF0);  // 分频因子
    Oled_WriteCmd(0xD9);  // 设置预充电周期
    Oled_WriteCmd(0x22);
    Oled_WriteCmd(0xDA);  // 设置COM引脚配置
    Oled_WriteCmd(0x12);
    Oled_WriteCmd(0xDB);  // 设置VCOMH
    Oled_WriteCmd(0x20);
    Oled_WriteCmd(0x8D);  // 使能电荷泵
    Oled_WriteCmd(0x14);
    Oled_WriteCmd(0xAF);  // 开启显示

    Oled_Clear();
    Oled_Refresh();
}

void Oled_Clear(void)
{
    memset(s_gram, 0, sizeof(s_gram));
}

void Oled_Refresh(void)
{
    uint8_t page, col;

    for (page = 0; page < OLED_PAGE_NUM; page++)
    {
        Oled_WriteCmd(0xB0 + page);  // 设置页地址
        Oled_WriteCmd(0x00);         // 设置列低位
        Oled_WriteCmd(0x10);         // 设置列高位

        for (col = 0; col < OLED_WIDTH; col++)
        {
            Oled_WriteData(s_gram[page][col]);
        }
    }
}

void Oled_DisplayOn(void)
{
    Oled_WriteCmd(0xAF);
}

void Oled_DisplayOff(void)
{
    Oled_WriteCmd(0xAE);
}

/* ========== 绘图函数 ========== */

void Oled_DrawPixel(uint8_t x, uint8_t y, uint8_t on)
{
    uint8_t page, bit;

    if (x >= OLED_WIDTH || y >= OLED_HEIGHT)
        return;

    page = y / 8;
    bit = y % 8;

    if (on)
        s_gram[page][x] |= (1 << bit);
    else
        s_gram[page][x] &= ~(1 << bit);
}

void Oled_ShowChar(uint8_t x, uint8_t y, char ch)
{
    uint8_t i, page, col_start;
    uint8_t index;

    if (x >= 16 || y >= 4)
        return;

    // 简化版：只显示空格、数字、字母、部分符号
    if (ch < 0x20 || ch > 0x7E)
        ch = ' ';

    index = FONT_INDEX(ch);
    col_start = x * 8;
    page = y * 2;

    // 8x16字体占2页
    for (i = 0; i < 8; i++)
    {
        if (col_start + i < OLED_WIDTH)
        {
            s_gram[page][col_start + i] = s_font8x16[index][i];
            s_gram[page + 1][col_start + i] = s_font8x16[index][i + 8];
        }
    }
}

void Oled_ShowString(uint8_t x, uint8_t y, const char *str)
{
    while (*str)
    {
        if (x >= 16)
            break;

        Oled_ShowChar(x, y, *str);
        str++;
        x++;
    }
}

void Oled_ShowNum(uint8_t x, uint8_t y, int32_t num, uint8_t len)
{
    char buf[12];
    uint8_t i, j;
    uint8_t neg = 0;

    if (num < 0)
    {
        neg = 1;
        num = -num;
    }

    // 转换为字符串（逆序）
    i = 0;
    do
    {
        buf[i++] = (num % 10) + '0';
        num /= 10;
    } while (num > 0);

    if (neg)
        buf[i++] = '-';

    // 补空格
    while (i < len)
        buf[i++] = ' ';

    // 反转并显示
    for (j = 0; j < len && j < i; j++)
    {
        Oled_ShowChar(x + j, y, buf[i - 1 - j]);
    }
}

void Oled_ShowVoltage(uint8_t x, uint8_t y, int32_t mv, uint8_t decimal)
{
    char buf[16];
    uint8_t i = 0;
    int32_t intPart, fracPart;

    intPart = mv / 1000;
    fracPart = mv % 1000;

    // 整数部分
    if (intPart == 0)
    {
        buf[i++] = '0';
    }
    else
    {
        char temp[8];
        uint8_t j = 0;
        while (intPart > 0)
        {
            temp[j++] = (intPart % 10) + '0';
            intPart /= 10;
        }
        while (j > 0)
        {
            buf[i++] = temp[--j];
        }
    }

    // 小数点
    buf[i++] = '.';

    // 小数部分
    if (decimal >= 3)
    {
        buf[i++] = (fracPart / 100) + '0';
        buf[i++] = ((fracPart / 10) % 10) + '0';
        buf[i++] = (fracPart % 10) + '0';
    }
    else if (decimal == 2)
    {
        buf[i++] = (fracPart / 100) + '0';
        buf[i++] = ((fracPart / 10) % 10) + '0';
    }
    else
    {
        buf[i++] = (fracPart / 100) + '0';
    }

    buf[i] = '\0';

    Oled_ShowString(x, y, buf);
}

/**
 * @brief  显示中文字符串（16x16字体）
 * @param  x: 起始列位置 (0~15)
 * @param  y: 行位置 (0~3，中文占2行高度)
 * @param  str: UTF-8编码的中文字符串
 */
void Oled_ShowChinese(uint8_t x, uint8_t y, const char *str)
{
    if (str == NULL)
        return;

    uint8_t col = x * 8;  // 转换为像素列
    uint8_t page = y * 2; // 中文占2页（16像素高）
    const char *p = str;

    while (*p != '\0')
    {
        // UTF-8 中文字符占3字节
        if ((*p & 0x80) != 0)
        {
            // 查找字库
            const uint8_t *fontData = FontCN_GetData(p);

            if (fontData != NULL)
            {
                // 绘制16x16点阵（上8行）
                for (uint8_t i = 0; i < 16; i++)
                {
                    if (col + i >= OLED_WIDTH)
                        break;

                    s_gram[page][col + i] = fontData[i];
                }

                // 绘制16x16点阵（下8行）
                if (page + 1 < OLED_PAGE_NUM)
                {
                    for (uint8_t i = 0; i < 16; i++)
                    {
                        if (col + i >= OLED_WIDTH)
                            break;

                        s_gram[page + 1][col + i] = fontData[16 + i];
                    }
                }

                col += 16;  // 一个汉字宽16像素
            }

            // 跳过3字节UTF-8字符
            p += 3;
        }
        else
        {
            // ASCII字符，跳过
            p++;
        }
    }
}
