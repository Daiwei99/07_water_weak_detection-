#ifndef __INT_RELAY_H
#define __INT_RELAY_H

#include "stm32f10x.h"

/*==============================================================================
 * 继电器控制
 *
 * 原理图上 RELAY = PB14 -> R30(2k) -> Q4 -> K1 线圈 -> GND
 * Q4 是 NPN 三极管，PB14 高电平时 Q4 导通，继电器线圈通电，触点吸合。
 *
 * 用途：断线或水浸报警时切断负载电源 / 触发外部报警设备。
 *
 * 注意：继电器有动作延时（典型 10~20ms），调用 Relay_On/Off 后不会立即
 *       切换到位。如果需要确认触点状态才能继续，调用后要 Delay_ms(30)。
 *============================================================================*/

void Relay_Init(void);

/* 继电器吸合（触点闭合） */
void Relay_On(void);

/* 继电器释放（触点断开） */
void Relay_Off(void);

#endif /* __INT_RELAY_H */
