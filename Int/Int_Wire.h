#ifndef __BSP_WIRE_H
#define __BSP_WIRE_H

#include "stm32f10x.h"

/*==============================================================================
 * 线缆通路控制层
 *
 * 管两块模拟开关芯片：
 *   U4 = 74HC4066D  四路独立模拟开关，控制"哪根线供电 / 哪根线接取样电阻"
 *   U7 = HEF4052BT  双 4 选 1 多路选择器，控制"ADC 采到哪根线"
 *
 * 【取样电阻是 R11 = 3.9kΩ，不是 R9】
 *   需求文档里写的"R9 电阻"是旧版图纸编号。在第 2 版原理图上：
 *     R9  = 10kΩ，在蜂鸣器电路里给 BUZZER1 正端上拉到 5V，与检测无关；
 *     R11 = 3.9kΩ，绿线(3Y)/黑线(4Y) 经 4066 汇流后经它接地，才是取样电阻。
 *   公式里的常数 4000 就是 R11 按 4kΩ 取整来的（3.9k ≈ 4k）。
 *   函数名沿用 R9 是为了和需求文档对得上，但实际操作的是 R11。
 *
 * 【4066 的四路对应关系】（原理图 U4，高电平使能）
 *   1E=PB4  -> 1Y = RED    经 R12(100Ω) 到 3V3   => 红线供电
 *   2E=PB3  -> 2Y = YELLOW 经 R16(100Ω) 到 3V3   => 黄线供电
 *   3E=PA15 -> 3Y = GREEN  汇到 R11(3.9k) 到 GND => 绿线接取样电阻
 *   4E=PB5  -> 4Z = BLACK  汇到 R11(3.9k) 到 GND => 黑线接取样电阻
 *   供电侧串 100Ω 是限流，取样侧共用一个 3.9k。
 *
 * 【PA15/PB3/PB4 的坑】
 *   这三个引脚复位后属于 JTAG-DP（JTDI/JTDO/JNTRST）。本板调试走 SWD
 *   （PA13/PA14，见 P3 排针），必须先在 Board_Init() 里关掉 JTAG 才能当
 *   普通 GPIO。漏掉那一步的话，红线供电/黄线供电/绿线接R11 三路全部失效，
 *   而且 GPIO 读写看起来完全正常，很难查。
 *============================================================================*/

/*------------------------------------------------------------------------------
 * 4052 通道选择：PB6 = S1 = IO1（低位），PB7 = S2 = IO2（高位）
 *
 * 4052 是双路的：bank1 的 1Y0~1Y3 选通到 1Z -> R14(0Ω) -> 网络 ADC0 -> PA1
 *                bank2 的 2Y0~2Y3 选通到 2Z -> R15(0Ω) -> 网络 ADC1 -> PA2
 * 两个 bank 共用同一组地址线 S1/S2，所以一次切换同时决定 ADC0 和 ADC1 采谁。
 * 每路输入都串了 2kΩ 保护电阻（bank1: R22/R24/R26/R19，bank2: R28/R23/R27/R25）。
 *
 * 【E# 使能引脚已接地，代码不用管】
 *   HEF4052B 的 pin 6 = E# 是低电平有效的总使能，E# 为高时两个 bank 全部
 *   关断、1Z/2Z 悬空。原理图上 pin 6 直接接 GND（pin 7 VEE、pin 8 VSS 同样
 *   接地），所以芯片始终使能，不需要 GPIO 控制。
 *   如果哪天改板把 E# 引到 MCU，忘了拉低的现象是"ADC 恒读 0 或乱飘"。
 *
 * 【VDD = 3V3，不是 5V】
 *   原理图 pin 16 -> 3V3。手册的 RON 参数（典型 115Ω / 最大 340Ω）是在
 *   VDD-VEE = 5V 下测的，3.3V 供电时 RON 更大，影响 ADC 采样时间的选择，
 *   见 Int_Adc.c 顶部的源阻抗计算。
 *   另外这也限定了被测信号必须在 0~3.3V 内 —— 线缆激励源就是 3V3，没问题。
 *
 * 原理图上的接线（已与需求文档"ADC通道配置"表逐行核对一致）：
 *   通道号 = S1 + 2*S2
 *
 *   S1(PB6) S2(PB7)  通道  ADC0(1Z/PA1)  ADC1(2Z/PA2)
 *      0       0       0    黄线(1Y0)     黑线(2Y0)
 *      1       0       1    绿线(1Y1)     黄线(2Y1)
 *      0       1       2    红线(1Y2)     绿线(2Y2)
 *      1       1       3    R11 上端(1Y3) R11 下端(2Y3)
 *
 * 枚举名按 "ADC0采的线_ADC1采的线" 命名，避免用的时候记反。
 *----------------------------------------------------------------------------*/
typedef enum
{
    WIRE_PATH_YELLOW_BLACK = 0,  /* S1=0 S2=0 : ADC0=黄, ADC1=黑      */
    WIRE_PATH_GREEN_YELLOW = 1,  /* S1=1 S2=0 : ADC0=绿, ADC1=黄      */
    WIRE_PATH_RED_GREEN    = 2,  /* S1=0 S2=1 : ADC0=红, ADC1=绿      */
    WIRE_PATH_R11_HI_LO    = 3   /* S1=1 S2=1 : ADC0=R11上, ADC1=R11下 */
} WirePath_t;

/* 模拟开关切换后需要等电压稳定才能采样。
 * 需求文档第五节"硬件保护"建议 >10ms，这里取 15ms 留余量。
 * 这个值是阶段一要实测标定的四个参数之一：4066 导通只要几百 ns，真正慢的是
 * 旁路电容 C7~C10(100nF) 配上 3.9k 取样电阻的 RC 充放电（τ≈0.39ms），
 * 理论上 2ms 就够，15ms 是保守值。实测确认后可以调小来提高扫描速度。 */
#define WIRE_SETTLE_MS      15U

void Wire_Init(void);

/*--- 4066 四路开关，参数 0 = 断开，非 0 = 接通 ------------------------------*/
void Wire_SetRedPower(uint8_t on);      /* PB4 : 红线接 3V3        */
void Wire_SetYellowPower(uint8_t on);   /* PB3 : 黄线接 3V3        */
void Wire_SetGreenToR9(uint8_t on);     /* PA15: 绿线接 R11 到 GND */
void Wire_SetBlackToR9(uint8_t on);     /* PB5 : 黑线接 R11 到 GND */

/* 一次性设置四路，参数顺序 = 红、黄、绿、黑。
 * 推荐用这个而不是分别调用：分开调用会产生中间状态，比如"红黄同时供电"
 * 到"只有红供电"的过程中可能瞬间出现两边都断开，采样时序不好控。 */
void Wire_SetSwitches(uint8_t red, uint8_t yellow, uint8_t green, uint8_t black);

/* 四路全断开。切换测量项之前先调用，避免上一项的通路残留。 */
void Wire_AllOff(void);

/* 选择 4052 通道 */
void Wire_SelectPath(WirePath_t path);

/* 设开关 + 选通道 + 等稳定，一步到位。
 * Measure 层的每一项测量都用它，保证"先建立通路，再等 RC 稳定，才采样"。 */
void Wire_Apply(uint8_t red, uint8_t yellow, uint8_t green, uint8_t black,
                WirePath_t path);

#endif /* __BSP_WIRE_H */
